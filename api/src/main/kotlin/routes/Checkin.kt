package eu.kasify.routes

import eu.kasify.RateLimitProviders
import eu.kasify.maybeRateLimit
import eu.kasify.model.api.requests.GuestRegistrationRequest
import eu.kasify.model.api.responses.CheckinResponse
import eu.kasify.routes.extensions.getBookingCode
import eu.kasify.services.CheckinService
import eu.kasify.versionedRouting
import io.ktor.http.HttpStatusCode
import io.ktor.openapi.jsonSchema
import io.ktor.server.application.Application
import io.ktor.server.request.receive
import io.ktor.server.response.respond
import io.ktor.server.routing.get
import io.ktor.server.routing.openapi.describe
import io.ktor.server.routing.post
import io.ktor.utils.io.ExperimentalKtorApi
import org.koin.ktor.ext.inject

@OptIn(ExperimentalKtorApi::class)
fun Application.configureCheckinRouting() {
    val checkinService by inject<CheckinService>()

    versionedRouting {
        // Public guest check-in surface — layered limits: per-IP catches
        // mass scraping, per-code catches booking-code brute-force.
        maybeRateLimit(RateLimitProviders.IpCheckin) {
            maybeRateLimit(RateLimitProviders.CheckinCode) {
                // Public guest check-in endpoint (no auth — accessed via check-in code link)
                get("/checkin/{code}") {
                    val code = call.getBookingCode()
                    call.respond(checkinService.getCheckinSnapshot(code))
                }.describe {
                    tag("Checkin")
                    summary = "Get check-in snapshot"
                    description = "Public endpoint. Returns the booking, property, and already-registered guests for the given check-in code so the guest-facing check-in form can render."
                    parameters {
                        path("code") { description = "Booking check-in code (high-entropy public identifier generated by Kasify and shared with the guest)" }
                    }
                    responses {
                        HttpStatusCode.OK {
                            description = "Check-in snapshot"
                            schema = jsonSchema<CheckinResponse>()
                        }
                        HttpStatusCode.NotFound { description = "No booking matches this check-in code, or the property is missing" }
                    }
                }

                // Public guest registration — saves a single guest for the booking and returns
                // the updated check-in snapshot. Validation is enforced by RequestValidation,
                // see GuestRegistrationRequest.validate() for the SES Hospedajes rules.
                post("/checkin/{code}/guests") {
                    val code = call.getBookingCode()
                    val request = call.receive<GuestRegistrationRequest>()
                    call.respond(HttpStatusCode.Created, checkinService.registerGuest(code, request))
                }.describe {
                    tag("Checkin")
                    summary = "Register guest"
                    description = "Public endpoint. Registers one guest against the booking and returns the updated check-in snapshot."
                    parameters {
                        path("code") { description = "Booking check-in code" }
                    }
                    requestBody {
                        description = "Guest details conforming to SES Hospedajes requirements"
                        required = true
                        schema = jsonSchema<GuestRegistrationRequest>()
                    }
                    responses {
                        HttpStatusCode.Created {
                            description = "Updated check-in snapshot including the new guest"
                            schema = jsonSchema<CheckinResponse>()
                        }
                        HttpStatusCode.BadRequest {
                            description = "Validation failed, or check-in is closed (`checkin.closed`), or the booking is already full (`checkin.booking_full`)"
                        }
                        HttpStatusCode.NotFound { description = "Booking or property not found for this check-in code" }
                    }
                }
            }
        }
    }
}
